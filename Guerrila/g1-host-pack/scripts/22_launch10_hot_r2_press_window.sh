append_api_key_if_needed() {
    local url="$1"
    local api_key="$2"
    if is_placeholder_value "$url" || is_placeholder_value "$api_key"; then
        printf '%s\n' "$url"
        return 0
    fi
    if [[ "$url" == *"api-key="* || "$url" == *"apikey="* ]]; then
        printf '%s\n' "$url"
        return 0
    fi
    if [[ "$url" == *"?"* ]]; then
        printf '%s&api-key=%s\n' "$url" "$api_key"
    else
        printf '%s?api-key=%s\n' "$url" "$api_key"
    fi
}

