#!/usr/bin/env bash
# 22_launch53_r3_batch002_frozen_runner.sh — exact Batch002-style R3 baseline runner.
#
# Purpose:
#   Keep the last clean positive Launch phenotype separate from the later R4
#   broad/clone experiments. This wrapper intentionally recreates the Batch002
#   operating contract instead of inheriting newer R4 defaults from Launch13.
set -euo pipefail

source_crlf_safe() {
    local path="$1"
    # shellcheck disable=SC1090
    source /dev/stdin <<<"$(tr -d '\r' < "$path")"
}

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
source_crlf_safe "$SCRIPT_DIR/lib.sh"
script_header "22 Launch53 — R3 Batch002 Frozen Baseline Runner"

WINDOW_SECONDS="${1:-${SHADOW_LAUNCH53_WINDOW_SECONDS:-3600}}"

# Batch002 identity. Use the old R3 contract, not the experimental R4 hunter
# contract. These exports are explicit so newer Launch13 defaults cannot leak in.
export SHADOW_RISK_TIER="${SHADOW_RISK_TIER:-R3_COLD_CAPITAL_PRESS}"
export SHADOW_LAUNCH_R2_HOLD_MODE="true"
export SHADOW_LAUNCH_HUNTER_MODE="false"
export SHADOW_LAUNCH_HOLD_V2_ENABLED="false"
export SHADOW_LAUNCH_BATCH002_SIMILARITY_REQUIRED="false"
export SHADOW_LAUNCH_STOP_AFTER_SUCCESS="${SHADOW_LAUNCH_STOP_AFTER_SUCCESS:-false}"

# Batch002 sizing and accounting.
export SHADOW_R2_MAX_SPEND_SOL="${SHADOW_R2_MAX_SPEND_SOL:-0.01}"
export SHADOW_R2_MAX_LOSS_SOL="${SHADOW_R2_MAX_LOSS_SOL:-0.015}"
export SHADOW_R2_MAX_CASH_AT_RISK_SOL="${SHADOW_R2_MAX_CASH_AT_RISK_SOL:-0.025}"
export SHADOW_R2_MAX_ATTEMPTS="${SHADOW_R2_MAX_ATTEMPTS:-3}"
export SHADOW_R3_DAILY_LOSS_CAP_SOL="${SHADOW_R3_DAILY_LOSS_CAP_SOL:-0.03}"
export SHADOW_LAUNCH_INLINE_ACCOUNT_RECOVERY_PROVEN="${SHADOW_LAUNCH_INLINE_ACCOUNT_RECOVERY_PROVEN:-true}"

# Batch002 freshness and entry quality. Do not require R4/batch-clone similarity,
# broad hunter admission, or later entry-edge heuristics.
export SHADOW_LAUNCH_SIGNAL_MAX_AGE_MS="${SHADOW_LAUNCH_SIGNAL_MAX_AGE_MS:-5000}"
export SHADOW_LAUNCH_SIGNAL_AGED_QUALITY_MAX_AGE_MS="${SHADOW_LAUNCH_SIGNAL_AGED_QUALITY_MAX_AGE_MS:-8000}"
export SHADOW_LAUNCH_SIGNAL_SOFT_MAX_AGE_MS="${SHADOW_LAUNCH_SIGNAL_SOFT_MAX_AGE_MS:-8000}"
export SHADOW_LAUNCH_ALLOW_AGED_SIGNAL_IF_QUALITY_VALID="${SHADOW_LAUNCH_ALLOW_AGED_SIGNAL_IF_QUALITY_VALID:-true}"
export SHADOW_LAUNCH_ENTRY_QUALITY_ENABLED="${SHADOW_LAUNCH_ENTRY_QUALITY_ENABLED:-true}"
export SHADOW_LAUNCH_ENTRY_QUALITY_MIN_PRICE_CHANGE_BPS="${SHADOW_LAUNCH_ENTRY_QUALITY_MIN_PRICE_CHANGE_BPS:-100}"
export SHADOW_LAUNCH_ENTRY_QUALITY_WINDOW_MS="${SHADOW_LAUNCH_ENTRY_QUALITY_WINDOW_MS:-2000}"
export SHADOW_LAUNCH_ENTRY_QUALITY_MAX_SELL_COUNT_2S="${SHADOW_LAUNCH_ENTRY_QUALITY_MAX_SELL_COUNT_2S:-0}"
export SHADOW_LAUNCH_ENTRY_EDGE_ENABLED="false"

# Batch002 exit shape: cost-protector/trailing was the money path. Keep the
# catastrophic safety stack, but do not enable newer R4-only weakening/pre-arm
# experiments as entry/exit policy for this frozen baseline.
export SHADOW_LAUNCH_EXIT_HARD_STOP_BPS="${SHADOW_LAUNCH_EXIT_HARD_STOP_BPS:-1000}"
export SHADOW_LAUNCH_EXIT_TRAILING_STOP_BPS="${SHADOW_LAUNCH_EXIT_TRAILING_STOP_BPS:-1500}"
export SHADOW_LAUNCH_EXIT_DROP_10S_BPS="${SHADOW_LAUNCH_EXIT_DROP_10S_BPS:-800}"
export SHADOW_LAUNCH_EXIT_MAX_HOLD_SECONDS="${SHADOW_LAUNCH_EXIT_MAX_HOLD_SECONDS:-3600}"
export SHADOW_LAUNCH_COST_PROFIT_PROTECTOR_ENABLED="${SHADOW_LAUNCH_COST_PROFIT_PROTECTOR_ENABLED:-true}"
export SHADOW_LAUNCH_COST_PROFIT_BUFFER_BPS="${SHADOW_LAUNCH_COST_PROFIT_BUFFER_BPS:-500}"
export SHADOW_LAUNCH_COST_PROFIT_TIGHT_TRAILING_BPS="${SHADOW_LAUNCH_COST_PROFIT_TIGHT_TRAILING_BPS:-500}"
export SHADOW_LAUNCH_PRE_ARM_WEAK_TIMEOUT_SECONDS="${SHADOW_LAUNCH_PRE_ARM_WEAK_TIMEOUT_SECONDS:-0}"
export SHADOW_LAUNCH_EXIT_QUOTE_WEAKENING_CHECKS="${SHADOW_LAUNCH_EXIT_QUOTE_WEAKENING_CHECKS:-0}"
export SHADOW_LAUNCH_EXIT_QUOTE_WEAKENING_CONFIRM_EXIT_COUNT="${SHADOW_LAUNCH_EXIT_QUOTE_WEAKENING_CONFIRM_EXIT_COUNT:-0}"

# Launch13 requires both confirmation names in newer code paths.
export SHADOW_LAUNCH_EXECUTE_CONFIRM="${SHADOW_LAUNCH_EXECUTE_CONFIRM:-EXECUTE_LAUNCH_R3_BATCH002_FROZEN_001}"
export SHADOW_R2_EXECUTE_CONFIRM="${SHADOW_R2_EXECUTE_CONFIRM:-$SHADOW_LAUNCH_EXECUTE_CONFIRM}"
export SHADOW_R2_EXECUTE_CONFIRM_REQUIRED="${SHADOW_R2_EXECUTE_CONFIRM_REQUIRED:-$SHADOW_LAUNCH_EXECUTE_CONFIRM}"

exec "$SCRIPT_DIR/22_launch13_r2_hold_live_execute.sh" "$WINDOW_SECONDS"
