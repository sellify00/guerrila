#!/usr/bin/env bash
# 22_launch58b_b002_plus_active_curve_live_window.sh — fresh in-window B002_PLUS active-curve gate.
set -euo pipefail

source_crlf_safe() {
    local path="$1"
    # shellcheck disable=SC1090
    source /dev/stdin <<<"$(tr -d '\r' < "$path")"
}

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PACK_DIR="$(cd "$SCRIPT_DIR/.." && pwd)"
source_crlf_safe "$SCRIPT_DIR/lib.sh"
script_header "22 Launch58b — B002_PLUS Active-Curve Live Window"

assert_cmd_exists python3

WINDOW_SECONDS="${1:-${SHADOW_LAUNCH58B_WINDOW_SECONDS:-3600}}"
RESULTS_ROOT="${SHADOW_RESULTS_DIR:-$PACK_DIR/results}"
RUN_ID="$(date -u +%Y%m%dT%H%M%SZ)"
REPLAY_OUT_DIR="${SHADOW_LAUNCH58B_B002_REPLAY_OUT_DIR:-$RESULTS_ROOT/22_launch58b_b002_replay_$RUN_ID}"
REGRESSION_OUT_DIR="${SHADOW_LAUNCH58B_B002_REGRESSION_OUT_DIR:-$RESULTS_ROOT/22_launch58b_b002_regression_$RUN_ID}"
CAPTURE_SUMMARY_PATH="${SHADOW_LAUNCH_B002_PLUS_ACTIVE_CURVE_CAPTURE_SUMMARY_PATH:-$RESULTS_ROOT/22_launch54_birth_ramp_capture_sim/summary.json}"
EXECUTE_REQUIRED="${SHADOW_R2_EXECUTE_CONFIRM_REQUIRED:-EXECUTE_B002_PLUS_ACTIVE_CURVE_LIVE_WINDOW_001}"
EXECUTE_CONFIRM="${SHADOW_R2_EXECUTE_CONFIRM:-${SHADOW_LAUNCH_EXECUTE_CONFIRM:-$EXECUTE_REQUIRED}}"

[[ -f "$CAPTURE_SUMMARY_PATH" ]] || fail "Launch54 birth-ramp capture summary missing: $CAPTURE_SUMMARY_PATH"
if [[ $FAILURES -ne 0 ]]; then
    finish
    exit 1
fi

SHADOW_LAUNCH_B002_REPLAY_OUT_DIR="$REPLAY_OUT_DIR" \
    bash "$SCRIPT_DIR/22_launch_b002_replay_frozen.sh"
SHADOW_LAUNCH_B002_REGRESSION_OUT_DIR="$REGRESSION_OUT_DIR" \
    bash "$SCRIPT_DIR/22_launch_b002_regression_matrix.sh"

B002_REPLAY_STATUS="$(python3 - <<PY
import json
from pathlib import Path
p = Path("$REPLAY_OUT_DIR/summary.json")
data = json.loads(p.read_text(encoding="utf-8", errors="replace"))
print(data.get("status") or "")
PY
)"
B002_REGRESSION_STATUS="$(python3 - <<PY
import json
from pathlib import Path
p = Path("$REGRESSION_OUT_DIR/summary.json")
data = json.loads(p.read_text(encoding="utf-8", errors="replace"))
print(data.get("status") or "")
PY
)"

[[ "$B002_REPLAY_STATUS" == "B002_FROZEN_REPLAY_PASS" ]] || fail "B002 frozen replay failed: $B002_REPLAY_STATUS"
[[ "$B002_REGRESSION_STATUS" == "B002_REGRESSION_MATRIX_PASS" ]] || fail "B002 regression matrix failed: $B002_REGRESSION_STATUS"
if [[ $FAILURES -ne 0 ]]; then
    finish
    exit 1
fi

export SHADOW_RISK_TIER="${SHADOW_RISK_TIER:-B002_PLUS_ACTIVE_CURVE_LIVE_WINDOW}"
export SHADOW_LAUNCH_HOLD_V2_ENABLED="${SHADOW_LAUNCH_HOLD_V2_ENABLED:-true}"
export SHADOW_LAUNCH_STOP_AFTER_SUCCESS="${SHADOW_LAUNCH_STOP_AFTER_SUCCESS:-false}"
export SHADOW_R2_MAX_SPEND_SOL="${SHADOW_R2_MAX_SPEND_SOL:-0.01}"
export SHADOW_R2_MAX_LOSS_SOL="${SHADOW_R2_MAX_LOSS_SOL:-0.015}"
export SHADOW_R2_MAX_CASH_AT_RISK_SOL="${SHADOW_R2_MAX_CASH_AT_RISK_SOL:-0.025}"
export SHADOW_R2_MAX_ATTEMPTS="${SHADOW_R2_MAX_ATTEMPTS:-3}"

export SHADOW_LAUNCH_HUNTER_MODE="true"
export SHADOW_LAUNCH_BATCH002_SIMILARITY_REQUIRED="false"
export SHADOW_LAUNCH_B002_PLUS_REQUIRED="false"
export SHADOW_LAUNCH_B002_PLUS_ACTIVE_CURVE_REQUIRED="false"
export SHADOW_LAUNCH_B002_PLUS_ACTIVE_CURVE_LIVE_WINDOW_REQUIRED="true"
export SHADOW_LAUNCH_B002_PLUS_ACTIVE_CURVE_B002_REPLAY_STATUS="$B002_REPLAY_STATUS"
export SHADOW_LAUNCH_B002_PLUS_ACTIVE_CURVE_REGRESSION_STATUS="$B002_REGRESSION_STATUS"
export SHADOW_LAUNCH_B002_PLUS_ACTIVE_CURVE_CAPTURE_SUMMARY_PATH="$CAPTURE_SUMMARY_PATH"

export SHADOW_LAUNCH_ENTRY_QUALITY_ENABLED="${SHADOW_LAUNCH_ENTRY_QUALITY_ENABLED:-false}"
export SHADOW_LAUNCH_ENTRY_EDGE_ENABLED="${SHADOW_LAUNCH_ENTRY_EDGE_ENABLED:-false}"
export SHADOW_LAUNCH_SIGNAL_MAX_AGE_MS="${SHADOW_LAUNCH_SIGNAL_MAX_AGE_MS:-60000}"
export SHADOW_LAUNCH_SIGNAL_AGED_QUALITY_MAX_AGE_MS="${SHADOW_LAUNCH_SIGNAL_AGED_QUALITY_MAX_AGE_MS:-60000}"
export SHADOW_LAUNCH_SIGNAL_SOFT_MAX_AGE_MS="${SHADOW_LAUNCH_SIGNAL_SOFT_MAX_AGE_MS:-60000}"
export SHADOW_LAUNCH_INLINE_ACCOUNT_RECOVERY_PROVEN="${SHADOW_LAUNCH_INLINE_ACCOUNT_RECOVERY_PROVEN:-true}"
export SHADOW_LAUNCH_EXIT_QUOTE_WEAKENING_CHECKS="${SHADOW_LAUNCH_EXIT_QUOTE_WEAKENING_CHECKS:-3}"
export SHADOW_LAUNCH_EXIT_QUOTE_WEAKENING_CONFIRM_EXIT_COUNT="${SHADOW_LAUNCH_EXIT_QUOTE_WEAKENING_CONFIRM_EXIT_COUNT:-3}"

export SHADOW_R2_EXECUTE_CONFIRM="$EXECUTE_CONFIRM"
export SHADOW_R2_EXECUTE_CONFIRM_REQUIRED="$EXECUTE_REQUIRED"

info "Launch58b class proof: replay=$B002_REPLAY_STATUS regression=$B002_REGRESSION_STATUS"
info "Launch58b execute_confirm=$SHADOW_R2_EXECUTE_CONFIRM required=$SHADOW_R2_EXECUTE_CONFIRM_REQUIRED"

exec "$SCRIPT_DIR/22_launch13_r2_hold_live_execute.sh" "$WINDOW_SECONDS"
