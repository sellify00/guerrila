#!/usr/bin/env bash
# 22_launch46_r4_b002_clone_runner.sh — R4 live runner restricted to Batch002-like candidates
set -euo pipefail

source_crlf_safe() {
    local path="$1"
    # shellcheck disable=SC1090
    source /dev/stdin <<<"$(tr -d '\r' < "$path")"
}

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PACK_DIR="$(cd "$SCRIPT_DIR/.." && pwd)"
source_crlf_safe "$SCRIPT_DIR/lib.sh"
script_header "22 Launch46 — R4 Batch002-Clone Runner"

WINDOW_SECONDS="${1:-${SHADOW_LAUNCH46_WINDOW_SECONDS:-3600}}"
RESULTS_ROOT="${SHADOW_RESULTS_DIR:-$PACK_DIR/results}"
FINGERPRINT_PATH="${SHADOW_LAUNCH_BATCH002_FINGERPRINT_PATH:-${SHADOW_LAUNCH46_FINGERPRINT_PATH:-$RESULTS_ROOT/22_launch44_batch002_fingerprint/fingerprint.json}}"
[[ -f "$FINGERPRINT_PATH" ]] || fail "Batch002 fingerprint missing: $FINGERPRINT_PATH; run 22_launch44 first"

export SHADOW_RISK_TIER="${SHADOW_RISK_TIER:-R4_B002_CLONE_LIVE}"
export SHADOW_LAUNCH_HUNTER_MODE="${SHADOW_LAUNCH_HUNTER_MODE:-true}"
export SHADOW_LAUNCH_HOLD_V2_ENABLED="${SHADOW_LAUNCH_HOLD_V2_ENABLED:-true}"
export SHADOW_LAUNCH_STOP_AFTER_SUCCESS="${SHADOW_LAUNCH_STOP_AFTER_SUCCESS:-false}"
export SHADOW_LAUNCH_BATCH002_SIMILARITY_REQUIRED="${SHADOW_LAUNCH_BATCH002_SIMILARITY_REQUIRED:-true}"
export SHADOW_LAUNCH_BATCH002_FINGERPRINT_PATH="$FINGERPRINT_PATH"

export SHADOW_R2_MAX_SPEND_SOL="${SHADOW_R2_MAX_SPEND_SOL:-0.01}"
export SHADOW_R2_MAX_LOSS_SOL="${SHADOW_R2_MAX_LOSS_SOL:-0.015}"
export SHADOW_R2_MAX_CASH_AT_RISK_SOL="${SHADOW_R2_MAX_CASH_AT_RISK_SOL:-0.025}"
export SHADOW_R2_MAX_ATTEMPTS="${SHADOW_R2_MAX_ATTEMPTS:-20}"
export SHADOW_LAUNCH_MAX_CONCURRENT_POSITIONS="${SHADOW_LAUNCH_MAX_CONCURRENT_POSITIONS:-1}"
export SHADOW_LAUNCH5_DAILY_MAX_TRADES="${SHADOW_LAUNCH5_DAILY_MAX_TRADES:-$SHADOW_R2_MAX_ATTEMPTS}"

# Batch002-clone HOLD should breathe: quote weakening warns/tightens unless it becomes
# collapse, and weak pre-arm positions are not forced out on a scalp-length timer.
export SHADOW_LAUNCH_EXIT_QUOTE_WEAKENING_CHECKS="${SHADOW_LAUNCH_EXIT_QUOTE_WEAKENING_CHECKS:-3}"
export SHADOW_LAUNCH_EXIT_QUOTE_WEAKENING_CONFIRM_EXIT_COUNT="${SHADOW_LAUNCH_EXIT_QUOTE_WEAKENING_CONFIRM_EXIT_COUNT:-3}"
export SHADOW_LAUNCH_PRE_ARM_WEAK_TIMEOUT_SECONDS="${SHADOW_LAUNCH_PRE_ARM_WEAK_TIMEOUT_SECONDS:-900}"
export SHADOW_LAUNCH_PRE_ARM_MIN_GAIN_BPS="${SHADOW_LAUNCH_PRE_ARM_MIN_GAIN_BPS:-500}"

export SHADOW_LAUNCH_SIGNAL_MAX_AGE_MS="${SHADOW_LAUNCH_SIGNAL_MAX_AGE_MS:-60000}"
export SHADOW_LAUNCH_SIGNAL_AGED_QUALITY_MAX_AGE_MS="${SHADOW_LAUNCH_SIGNAL_AGED_QUALITY_MAX_AGE_MS:-60000}"
export SHADOW_LAUNCH_SIGNAL_SOFT_MAX_AGE_MS="${SHADOW_LAUNCH_SIGNAL_SOFT_MAX_AGE_MS:-60000}"

export SHADOW_LAUNCH_EXECUTE_CONFIRM="${SHADOW_LAUNCH_EXECUTE_CONFIRM:-EXECUTE_LAUNCH_R4_B002_CLONE_001}"
export SHADOW_R2_EXECUTE_CONFIRM="${SHADOW_R2_EXECUTE_CONFIRM:-$SHADOW_LAUNCH_EXECUTE_CONFIRM}"
export SHADOW_R2_EXECUTE_CONFIRM_REQUIRED="${SHADOW_R2_EXECUTE_CONFIRM_REQUIRED:-$SHADOW_LAUNCH_EXECUTE_CONFIRM}"

exec "$SCRIPT_DIR/22_launch37_r4_broad_new_mint_hunter.sh" "$WINDOW_SECONDS"
